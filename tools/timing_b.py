"""Раскладка реплик по времени под готовую озвучку 34.2 с.

Длительность фразы считается по числу звучащих символов, между фразами —
пауза. Коэффициенты подобраны так, чтобы сумма совпала с реальными 34.2 с,
которые вернул HeyGen.
"""
import json, re

TOTAL = 34.2
LEAD = 0.25          # аватар вдыхает до первого слова
PAUSE = 0.30         # пауза между фразами
TAIL = 0.35

SENT = [
    "Я удалила вкладку Чат Джи Пи Ти.",
    "Устала всё делать за него.",
    "Раньше он писал инструкции, а сайты и цифры были на мне.",
    "Теперь я ставлю задачу целиком.",
    "Агент сам работает в браузере: открывает страницы, ищет данные.",
    "Через плагины подключается к Диску, таблицам, Канве.",
    "И возвращает не инструкцию, а готовый файл.",
    "Пока он собирает, я занимаюсь другим.",
    "Нужен доступ — спросит.",
    "Пиши ДЕСКТОП в комментариях — пришлю ссылку и свою настройку.",
]

def voiced(s):
    return len(re.sub(r"[^\w]", "", s, flags=re.UNICODE))

w = [voiced(s) for s in SENT]
speech = TOTAL - LEAD - TAIL - PAUSE * (len(SENT) - 1)
rate = speech / sum(w)          # секунд на символ

rows = []
t = LEAD
for s, ww in zip(SENT, w):
    d = ww * rate
    rows.append({"text": s, "start": round(t, 2), "end": round(t + d, 2),
                 "dur": round(d, 2)})
    t += d + PAUSE

print(f"скорость: {1/rate:.1f} симв/с, речь {speech:.2f} с, всего {t - PAUSE + TAIL:.2f} с\n")
for r in rows:
    print(f"{r['start']:6.2f} – {r['end']:6.2f}  ({r['dur']:4.2f})  {r['text']}")

json.dump(rows, open("timing_b.json", "w"), ensure_ascii=False, indent=1)
